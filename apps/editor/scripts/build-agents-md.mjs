import {readFile, writeFile} from 'node:fs/promises'
import {resolve} from 'node:path'
import {fileURLToPath} from 'node:url'

const editorDirectory = resolve(fileURLToPath(new URL('..', import.meta.url)))
const template = await readFile(resolve(editorDirectory, 'src/data/AgentsMdTemplate.md'), 'utf8')
const publishGuide = await readFile(resolve(editorDirectory, 'src/data/AgentsPublishGuide.md'), 'utf8')
const newline = template.indexOf('\n')
const title = template.slice(0, newline)
const templateBody = template.slice(newline + 1).trim()
const contents = `## Contents

- [Game development](#notes-for-blitz-and-threepipe-game-development)
- [Components](#object3dcomponent)
- [ThreeViewer](#threeviewer-api)
- [Examples](#examples)
- [Publish](#publish)
- [Show the game in the editor](#show-the-game-in-the-editor)
- [Limits](#limits)`
const output = `<!-- Generated by scripts/build-agents-md.mjs. -->\n\n${title}\n\n${contents}\n\n${templateBody}\n\n${publishGuide.trim()}\n`

await writeFile(resolve(editorDirectory, 'public/agents.md'), output)
console.log('Generated public/agents.md')
